func TestPrepend_CrossFormat_MigrationThenIdempotent(t *testing.T) {
	dir := t.TempDir()
	// Start with Apache
	style := &language.Style{LinePrefix: "//"}
	apacheHdr := (&ApacheLongFormat{}).Generate(style, "2025", "OldCorp", "Apache-2.0")
	p := writeTempFile(t, dir, "main.go", apacheHdr+"\n\npackage main\n")

	// Migrate to SPDX
	spdxFmt := &SPDXFormat{}
	newHdr := spdxFmt.Generate(style, "2026", "NewCorp", "MIT")
	if err := Prepend(p, style, newHdr, spdxFmt); err != nil {
		t.Fatal(err)
	}

	// Run Prepend again — should be idempotent
	if err := Prepend(p, style, newHdr, spdxFmt); err != nil {
		t.Fatal(err)
	}

	data, _ := os.ReadFile(p)
	content := string(data)
	if count := strings.Count(content, "SPDX-License-Identifier"); count != 1 {
		t.Errorf("expected 1 SPDX line after migration + re-run, got %d", count)
	}
	if strings.Contains(content, "Apache License") {
		t.Error("Apache header should not reappear")
	}
}

func TestPrepend_Idempotent(t *testing.T) {
	dir := t.TempDir()
	p := writeTempFile(t, dir, "main.go", "package main\n")
	style := &language.Style{LinePrefix: "//"}
	hdr := "// Copyright 2026 Acme\n// SPDX-License-Identifier: MIT"
	f := &SPDXFormat{}
	_ = Prepend(p, style, hdr, f)
	_ = Prepend(p, style, hdr, f)
	data, _ := os.ReadFile(p)
	if count := strings.Count(string(data), "SPDX-License-Identifier"); count != 1 {
		t.Errorf("expected 1 SPDX line, got %d", count)
	}
}

