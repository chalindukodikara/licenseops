func TestFix_MultipleCommentStyles(t *testing.T) {
	dir := t.TempDir()
	createFile(t, dir, "main.go", "package main\n")
	createFile(t, dir, "script.py", "print('hello')\n")
	createFile(t, dir, "query.sql", "SELECT 1;\n")
	cfg := testConfig(dir)
	cfg.License = "MIT"
	cfg.CopyrightHolder = ""
	eng, _ := New(cfg)
	result, _ := eng.Fix(false, false)
	if len(result.Fixed) != 3 {
		t.Errorf("expected 3 fixed, got %d", len(result.Fixed))
	}
	goData, _ := os.ReadFile(filepath.Join(dir, "main.go"))
	pyData, _ := os.ReadFile(filepath.Join(dir, "script.py"))
	sqlData, _ := os.ReadFile(filepath.Join(dir, "query.sql"))
	if !strings.HasPrefix(string(goData), "// SPDX") {
		t.Error("Go should use //")
	}
	if !strings.HasPrefix(string(pyData), "# SPDX") {
		t.Error("Python should use #")
	}
	if !strings.HasPrefix(string(sqlData), "-- SPDX") {
		t.Error("SQL should use --")
	}
}

// --- FixWithDiff ---

func TestFixWithDiff_ProducesDiff(t *testing.T) {
	dir := t.TempDir()
	createFile(t, dir, "main.go", "package main\n")
	eng, _ := New(testConfig(dir))
	result, err := eng.FixWithDiff(false)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.NonCompliant) != 1 {
		t.Errorf("expected 1 non-compliant, got %d", len(result.NonCompliant))
	}
	if len(result.Diffs) == 0 {
		t.Error("expected diffs to be populated")
	}
	for _, d := range result.Diffs {
		if !strings.Contains(d, "SPDX-License-Identifier") {
			t.Error("diff should contain the new header")
		}
		if !strings.Contains(d, "---") || !strings.Contains(d, "+++") {
			t.Error("diff should look like unified diff")
		}
	}
	// File should NOT be modified
	data, _ := os.ReadFile(filepath.Join(dir, "main.go"))
	if string(data) != "package main\n" {
		t.Error("FixWithDiff should not modify files")
	}
}

